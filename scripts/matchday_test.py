#!/usr/bin/env python3
"""ההצלבה מול לוח המשחקים: מה היא תופסת, ומה היא לא.

מועדון הכדורגל חולק איתנו את השם, ועונת הליגה שלו התחילה ב־15.9.2026.
מאז מגיע סיקור משחק שלו כל שבוע, ולכותרת כזאת אין שום סימן לענף. שלוש
כאלה נכנסו למדור בשלושה ימים, וכל אחת דרשה בדיקה ידנית.

מה שהכריע בכל שלוש הפעמים לא היה בכותרת אלא מחוצה לה: **לקבוצת הכדורסל
שלנו לא היה משחק באותו יום.** הכלל הופך את זה לבדיקה.

הקובץ הזה מודד שני דברים, ושניהם חשובים באותה מידה:

  * **דיוק.** אף כותרת כדורסל אמיתית לא נחסמת. זה התנאי הקשיח, כי כותרת
    שנעלמה לא משאירה סימן ואי אפשר לגלות אותה אחר כך.
  * **כיסוי.** כמה מכותרות הכדורגל האמיתיות הכלל באמת תופס. הוא לא תופס
    את כולן, וזה כתוב כאן במספר ולא כהבטחה.

כל התאריכים והכותרות אמיתיים, מהפיד.
"""

import datetime
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import news_feed


def t(s):
    return datetime.datetime.fromisoformat(s).replace(
        tzinfo=datetime.timezone.utc)


# לוח המשחקים שלנו כפי שהוא באמת בתקופה הזאת, בשעון UTC
FIXTURES = [t(x) for x in (
    "2026-08-31T17:05", "2026-09-04T10:00", "2026-09-08T16:00",
    "2026-09-12T13:30", "2026-09-13T16:30", "2026-09-18T11:30",
    "2026-09-25T11:00",
)]

# כותרות כדורגל אמיתיות שנכנסו למדור, עם מועד הפרסום שלהן. הדגל האחרון
# אומר אם הכותרת היא בכלל סיקור משחק. הכלל החדש מכוון רק לאלה, ולכן רק
# עליהן הוגן למדוד אותו: כותרת על שכר שחקנים או על מצב רוח בקבוצה היא
# כדורגל, אבל היא לא משחק ואף כלל של לוח משחקים לא יתפוס אותה.
SOCCER = [
    ("2026-09-16T04:59",
     'הפועל ירושלים שוב חזרה, ושוב מתוסכלת: "היה משחק שלנו"', True),
    ("2026-09-16T03:06", "שוב חוזר הניגון: תסכול עמוק בהפועל ירושלים", False),
    ("2026-09-16T13:20",
     "הפועל ירושלים מרוצה מהסגל: שיא זרים ושכר חסר תקדים", False),
    ("2026-09-15T06:02",
     "זדה הזהיר מהמעברים של טבריה, צ'ילופיה יקבל דקות ראשונות", False),
    # סיקור משחק כדורגל טיפוסי, כפי שהוא ייראה בשבועות הבאים
    ("2026-09-22T05:00", "הפועל ירושלים איבדה נקודות בדקה ה-90", True),
    ("2026-09-22T05:00", "1:2 והפועל ירושלים ממשיכה לרדוף", True),
]

# כותרות כדורסל אמיתיות שחייבות לעבור. **אף אחת מהן לא נחסמת** היא תנאי.
BASKET = [
    ("2026-09-18T12:43", 'ניצחון בצבע: הפועל י-ם גברה 69:83 על הפועל ב"ש'),
    ("2026-09-18T13:55", "הפועל ירושלים ניצחה את באר שבע/דימונה 69:83 "
                         "ועלתה לרבע גמר גביע ווינר"),
    ("2026-09-18T13:29", "שלשה אחת הספיקה: הפועל ירושלים העפילה לרבע גמר גביע ווינר"),
    ("2026-09-13T18:33", "הפועל י-ם הפסידה 104:95 לריטאס וילנה"),
    ("2026-09-12T11:50", "הכנה: הפועל ירושלים גברה 80:87 על אלופת היורוקאפ בורג"),
    ("2026-09-08T18:13", "הפועל ירושלים פתחה את העונה עם ניצחון 77:110 "
                         "על מכבי אשדוד בגביע ווינר"),
    # משחק שלנו שהלוח בכלל לא מכיר, בבלגרד. החלון של יומיים מכסה אותו
    # דרך המשחק של 31.8, וזו בדיוק הסיבה שהוא רחב.
    ("2026-09-01T20:58", "צפו: הפועל ירושלים ניצחה 80:87 את מכבי תל אביב בבלגרד"),
    # כותרות בלי משחק בכלל, שהכלל לא אמור לגעת בהן
    ("2026-09-15T16:22", "הפועל י-ם פנתה לאקס פורטלנד בלייק ווסלי"),
    ("2026-09-13T05:45", '"לא נשאיר את הסגל ככה": הפועל ירושלים מחפשת מחליף להארפר'),
    ("2026-09-17T16:38", "השם החדש שתראו על מדי הפועל ירושלים בעונה הקרובה"),
]


import contextlib


@contextlib.contextmanager
def without_hand_blocks():
    """מודדים בלי החסימות הידניות, אחרת המדידה משקרת לטובת הכלל.

    ארבע מכותרות הכדורגל שכאן כבר חסומות ביד ב־news-sources.json, כי
    חסמתי אותן בזמן אמת כשנכנסו למדור. אם משאירים אותן, כל כותרת נתפסת
    ב״כלל קיים״ והכלל החדש נראה מיותר, בעוד שהעבודה הידנית הזאת היא
    בדיוק מה שהוא בא לחסוך. אז מכבים אותן, ומודדים מה קורה בלעדיהן.
    """
    saved = news_feed._phrases_cache
    news_feed._phrases_cache = ()
    try:
        yield
    finally:
        news_feed._phrases_cache = saved


def main():
    fail = []
    print("כותרות כדורגל, ומי תופס כל אחת (בלי החסימות הידניות):")
    generic = new_rule = missed = 0
    reports = reports_generic = reports_new = 0
    with without_hand_blocks():
        for when, title, is_report in SOCCER:
            by_generic = not news_feed.about_us(title)
            by_new = bool(
                news_feed.other_sport_match_report(title, t(when), FIXTURES))
            reports += is_report
            if by_generic:
                generic += 1
                reports_generic += is_report
                tag = "כלל כללי "
            elif by_new:
                new_rule += 1
                reports_new += is_report
                tag = "הכלל החדש"
            else:
                missed += 1
                tag = "אף אחד   "
            kind = "משחק" if is_report else "אחר "
            print(f"  {tag} · {kind} · {title[:56]}")

    survived = len(SOCCER) - generic
    reports_left = reports - reports_generic
    print(f"\n  {generic} מתוך {len(SOCCER)} נחסמות בכללים הכלליים, "
          f"מהן {reports_generic} סיקורי משחק.")
    print(f"  {survived} שורדות אותם. סיקורי משחק ביניהן: {reports_left}, "
          f"ומהם הכלל החדש תופס {reports_new}.")
    if survived - reports_left:
        print(f"  {survived - reports_left} כותרות כדורגל שאינן משחק "
              f"שורדות הכול, ועליהן הכלל לא אמור לענות.")

    print("\nכותרות כדורסל, אף אחת לא נחסמת:")
    for when, title in BASKET:
        why = news_feed.other_sport_match_report(title, t(when), FIXTURES)
        if why:
            fail.append(f"נחסמה כותרת כדורסל: {title}\n      {why}")
            print("  נחסמה! " + title[:64])
        else:
            print("  עברה   " + title[:64])

    # **סימן הכדורסל נבדק בנפרד, כי הכותרות האמיתיות לא בודקות אותו.**
    # בכל הכותרות שלמעלה שני המגנים חופפים: לכולן יש משחק שלנו בסביבה,
    # אז החלון לבדו מספיק והסימן אף פעם לא מגיע לידי ביטוי. מדדתי את זה
    # במוטציה: מחקתי את בדיקת הסימן והמבחן עדיין עבר. לכן כאן לוקחים
    # כותרות כדורסל אמיתיות ומזיזים אותן לתאריך שבו לא שיחקנו, וזה
    # התרחיש שיקרה באמת כשאתר יפרסם סיקור או מבט לאחור כמה ימים אחרי
    # המשחק. התאריך כאן מומצא לצורך הבדיקה, הכותרות לא.
    print("\nסימן כדורסל עוצר את הכלל גם רחוק מהלוח:")
    far = t("2026-07-01T09:00")
    exposed = []
    for _, title in BASKET:
        blocked = bool(news_feed.other_sport_match_report(title, far, FIXTURES))
        has_sign = any(news_feed._norm(w) in news_feed._norm(title)
                       for w in news_feed.BASKET)
        if has_sign:
            if blocked:
                fail.append(f"סימן הכדורסל לא עצר: {title}")
                print("  נחסמה! " + title[:64])
            else:
                print("  עברה   " + title[:64])
        elif blocked:
            exposed.append(title)
    # **וזה הסיכון של הכלל, והוא כתוב כאן כמספר ולא כהערת שוליים.**
    # כותרת כדורסל בלי מילה מזהה, למשל ״הפועל י־ם הפסידה 104:95 לריטאס
    # וילנה״, מוגנת רק על ידי החלון. אם המשחק חסר מהלוח, או שהסיקור הגיע
    # יותר מיממה אחריו, היא תיחסם בשקט. לכן כל חסימה נכתבת ללוג, וזו
    # הדרך היחידה לגלות את זה בדיעבד.
    print(f"  {len(exposed)} מתוך {len(BASKET)} כותרות כדורסל מוגנות רק "
          f"על ידי הלוח, ואם הוא שגוי הן ייחסמו.")

    print("\nהכלל לא חל כשאין לוח:")
    for when, title, _ in SOCCER[:2]:
        if news_feed.other_sport_match_report(title, t(when), []):
            fail.append(f"הכלל חל בלי לוח: {title}")
    print("  תקין: בלי games.json שום כותרת לא נחסמת")

    if reports_new + reports_generic < reports:
        fail.append("סיקור משחק כדורגל עבר את כל השכבות")

    if fail:
        print(f"\nנשברו {len(fail)}:")
        for f in fail:
            print("   " + f)
        sys.exit(1)
    print(f"\nדיוק: {len(BASKET)} כותרות כדורסל עברו, אף אחת לא נחסמה.")
    print(f"כיסוי: כל {reports} סיקורי המשחק של הכדורגל נחסמים, "
          f"{reports_generic} בכללים הכלליים ו־{reports_new} בכלל החדש.")


if __name__ == "__main__":
    main()
