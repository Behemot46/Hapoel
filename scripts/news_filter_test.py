# מקורות שנחסמים לפי מארח ולא לפי כותרת, ולכן about_us לא רואה אותם
# בכלל. הבדיקה כאן היא שההגדרה ב־news-sources.json עדיין במקומה.
BLOCKED_HOSTS = ("365scores.com",)


def main():
    bad = []
    cfg_block = {b.lower() for b in news_feed._config()["block"]}
    for host in BLOCKED_HOSTS:
        if host not in cfg_block:
            bad.append(("מארח שהיה חסום כבר לא חסום", host))
    for t in SOCCER:
        if news_feed.about_us(t):
            bad.append(("עברה ולא הייתה צריכה", t))
    for t in BASKET:
        if not news_feed.about_us(t):
            bad.append(("נחסמה ולא הייתה צריכה", t))
    for t in MEETING_PAGE:
        if news_feed.about_us(t):
            bad.append(("עמוד מפגש עבר", t))

    live = news_feed.DATA / "news.json"
    if live.exists():
        import json
        items = json.loads(live.read_text(encoding="utf-8")).get("items", [])
        stuck = [i["title"] for i in items if not news_feed.about_us(i["title"])]
        if stuck:
            print(f"שימו לב: {len(stuck)} כותרות שכבר בקובץ החי לא היו עוברות היום:")
            for t in stuck:
                print("   -", t)
            print("הן ירדו באיסוף הבא. אם הן מפריעות עכשיו, מוחקים אותן מהקובץ ביד.")

    if bad:
        print(f"\n{len(bad)} כשלים:")
        for why, t in bad:
            print(f"  {why}: {t}")
        return 1
    print(f"\n{len(SOCCER)} כותרות כדורגל נחסמו, {len(BASKET)} כותרות כדורסל עברו, "
          f"{len(MEETING_PAGE)} עמודי מפגש נחסמו.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
