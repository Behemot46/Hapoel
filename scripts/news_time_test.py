#!/usr/bin/env python3
"""מועד הפרסום של כותרת לא זז אחרי שנרשם אצלנו.

גוגל מדווחת מועד מדויק כל עוד הידיעה טרייה, ומחליפה אותו אחרי כמה ימים
בתאריך גס: אותו יום בשעה 07:00. במדידה על היסטוריית news.json בגיט,
28 כותרות עברו ל־07:00 מזמן מדויק. בלי נעילה אנחנו דורסים בזמן הגס את
הזמן הנכון שכבר היה לנו, והאוהד רואה את זה גם בתאריך שמתחת לכותרת וגם
בסדר המדור, שממוין לפי הזמן.

כל הזוגות כאן אמיתיים, מתוך הגרסאות של הקובץ.
"""

import datetime
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import news_feed


def at(s):
    return datetime.datetime.fromisoformat(s.replace("Z", "+00:00"))


# (כותרת, מה שנרשם אצלנו, מה שגוגל דיווחה אחר כך)
DEGRADED = [
    ("הפועל ירושלים הביסה את בני הרצליה 68:88 ועלתה לחצי גמר גביע",
     "2026-09-25T12:58:00Z", "2026-09-25T07:00:00Z"),
    ("קני לופטון כיכב, הפועל י-ם העפילה לחצי הגמר",
     "2026-09-25T12:53:00Z", "2026-09-25T07:00:00Z"),
    ("באירופה כבר מסמנים את הפועל ירושלים: \"פוטנציאל ליורוליג\"",
     "2026-09-27T16:05:27Z", "2026-09-27T07:00:00Z"),
    ("הפועל ירושלים פתחה את העונה עם ניצחון 77:110 על מכבי אשדוד בגביע ווינר",
     "2026-09-08T18:13:00Z", "2026-09-08T07:00:00Z"),
    ("\"הפועל ירושלים עלולה לפספס שריון ביורוליג בגלל עופר ינאי\"",
     "2026-09-19T15:28:38Z", "2026-09-19T07:00:00Z"),
    ("הפועל י-ם הפסידה 104:95 לריטאס וילנה",
     "2026-09-13T18:33:00Z", "2026-09-13T07:00:00Z"),
]

# **הגבול של הנעילה, ובמבחן ולא רק בהערה.** הידיעה של 0404 על חצי הגמר
# של 4.10 מתוארכת ל־3.10, יום לפני המשחק, והזמן הזה היה שגוי כבר בתצפית
# הראשונה שלנו. אין מה לשחזר, והמבחן אומר את זה במקום להעמיד פנים:
# הנעילה שומרת על זמן שנרשם, היא לא מזהה זמן שגוי. הארץ סיקרה את אותו
# משחק בכותרת אחרת ובזמן נכון, ולכן זו גם לא כפילות שאפשר לנכש.
EARLY = ("מכבי ת\"א הביסה את הפועל י-ם 71:88 - ותפגוש את הפועל ת\"א בגמר גביע ווינר",
         "2026-10-03T07:00:00Z")
TIPOFF = at("2026-10-04T16:00:00Z")   # 19:00 שעון ישראל, מהלוח שלנו


def main():
    fail = []
    stored = [{"title": title, "published": ours} for title, ours, _ in DEGRADED]
    known = news_feed.first_seen(stored)

    print("כותרות שגוגל החליפה להן את הזמן:")
    for title, ours, theirs in DEGRADED:
        kept = news_feed.keep_first(known, title, at(theirs))
        ok = kept == at(ours)
        if not ok:
            fail.append(f"הזמן זז: {title[:46]} ({kept} במקום {ours})")
        print(f"  {'תקין' if ok else 'נפל!'} {theirs[:16]} -> "
              f"{kept.isoformat()[:16]}  {title[:42]}")

    title, theirs = EARLY
    kept = news_feed.keep_first(known, title, at(theirs))
    print("\nמה שהנעילה לא פותרת, כי הזמן היה שגוי מהתצפית הראשונה:")
    print(f"  סיקור של משחק שהתחיל {TIPOFF.isoformat()[:16]} מתוארך "
          f"{kept.isoformat()[:16]}, יום לפני")
    if kept != at(theirs):
        fail.append("הנעילה שינתה זמן של כותרת שלא ראינו קודם")

    # כותרת חדשה היא לא כותרת שהזמן שלה זז, ולוקחים לה את זמן הפיד כמו
    # שהוא. בלי התנאי הזה הנעילה הייתה אומרת ״אין זמן״ לכל ידיעה טרייה.
    fresh = at("2026-10-07T09:12:00Z")
    got = news_feed.keep_first(known, "כותרת שלא ראינו עדיין", fresh)
    print(f"\nכותרת חדשה מקבלת את זמן הפיד: {got.isoformat()[:16]}")
    if got != fresh:
        fail.append("כותרת חדשה לא קיבלה את זמן הפיד")

    # המפתח מתעלם מפיסוק ומרווחים, כמו בזיהוי הכפילויות, כי אתר ששינה
    # מרכאות או הוסיף רווח לא פרסם כותרת חדשה
    same = news_feed.keep_first(
        known, "  הפועל י-ם הפסידה 104:95 לריטאס וילנה!  ",
        at("2026-09-13T07:00:00Z"))
    print(f"אותה כותרת עם פיסוק אחר: {same.isoformat()[:16]}")
    if same != at("2026-09-13T18:33:00Z"):
        fail.append("שינוי פיסוק בכותרת שבר את הנעילה")

    # פריט שבור במדור הקיים לא מפיל את הטעינה ולא נועל כלום
    broken = news_feed.first_seen(
        [{"title": "בלי זמן"}, {"published": "2026-10-01T10:00:00Z"},
         {"title": "זמן לא קריא", "published": "אתמול"}])
    print(f"פריטים שבורים במדור הקיים: {len(broken)} נעילות")
    if broken:
        fail.append("פריט שבור יצר נעילה")

    if fail:
        print(f"\nנשברו {len(fail)}:")
        for f in fail:
            print("   " + f)
        sys.exit(1)
    print(f"\nכל {len(DEGRADED)} הזמנים שגוגל החליפה נשמרו כפי שנרשמו.")


if __name__ == "__main__":
    main()
