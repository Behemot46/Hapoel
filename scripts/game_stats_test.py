def main():
    fail = []

    print("שני הטפסים מסתדרים עם שורת הסה\"כ המודפסת:")
    teams = []
    for rows in (US, THEM):
        team = gs.team_from_rows(rows)
        teams.append(team)
        bad = gs.verify(team)
        print(f"  {'תקין' if not bad else 'נשבר'}: {team['name']} · "
              f"{len(team['players'])} שחקנים · {team['totals']['pts']} נק׳ · "
              f"מאמן {team['coach']}")
        for b in bad:
            print("      " + b)
        fail += [f"{team['name']}: {b}" for b in bad]

    # המספרים של לופטון, מול מה שדווח בכתבות: 17 נקודות, 10 ריבאונדים, 6 אסיסטים
